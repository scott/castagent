import {Args, Command, Flags} from '@oclif/core'
import * as fs from 'fs'
import * as os from 'os'
import * as path from 'path'
import {simpleGit, type SimpleGit} from 'simple-git'
import * as yaml from 'yaml'
import {ensureMemoryDatabaseIgnored, memoryNotesAreTracked, untrackMemoryNotes} from '../../lib/cast-ignore'

export default class GitCommit extends Command {
  static description = 'Commit changes to an agent repository'

  static examples = [
    '<%= config.bin %> git commit my-agent -m "Updated instructions"',
  ]

  static args = {
    agent: Args.string({description: 'Agent name', required: true}),
  }

  static flags = {
    message: Flags.string({
      char: 'm',
      description: 'Commit message',
      required: true,
    }),
  }

  private getAgentsDir(): string {
    return path.join(os.homedir(), '.cast', 'agents')
  }

  private isGitRepo(agentPath: string): boolean {
    return fs.existsSync(path.join(agentPath, '.git'))
  }

  private loadAgentConfig(agentPath: string): any {
    const configPath = path.join(agentPath, 'agent.yaml')
    if (fs.existsSync(configPath)) {
      const content = fs.readFileSync(configPath, 'utf-8')
      return yaml.parse(content) || {}
    }
    return {}
  }

  private regenerateReadme(agentPath: string): void {
    const config = this.loadAgentConfig(agentPath)
    const agentName = config.name || path.basename(agentPath)

    const description = config.description || 'No description provided'
    const model = config.brain?.model || 'Not specified'
    const version = config.version || '1.0'
    const runtime = config.runtime?.python_version || '3.11'

    const builtinTools = config.tools?.builtin || []
    const mcpServers = config.tools?.mcp || []
    const customTools = config.tools?.custom || []

    const formatList = (items: any[]): string => {
      if (!items || items.length === 0) return 'None'
      return items.map(item => {
        if (typeof item === 'string') return `- ${item}`
        return `- ${item.name || item.server || JSON.stringify(item)}`
      }).join('\n')
    }

    const readme = `# ${agentName}

${description}

## Configuration

- **Model:** ${model}
- **Runtime:** Python ${runtime}
- **Version:** ${version}

## Tools

### Built-in
${formatList(builtinTools)}

### MCP Servers
${formatList(mcpServers)}

### Custom
${formatList(customTools)}

## Setup

\`\`\`bash
# Clone this agent
cast clone <remote-url>

# Run the agent
cast dev ${agentName}
\`\`\`

## Files

- \`agent.yaml\` - Agent configuration
- \`instructions.md\` - System prompt
- \`tools/\` - Custom Python tools
- \`mcp/\` - MCP server configurations

---

*Generated by cast*
`

    const readmePath = path.join(agentPath, 'README.md')
    fs.writeFileSync(readmePath, readme)
  }

  async run(): Promise<void> {
    const {args, flags} = await this.parse(GitCommit)
    const agentName = args.agent
    const message = flags.message

    const agentsDir = this.getAgentsDir()
    const agentPath = path.join(agentsDir, agentName)

    if (!fs.existsSync(agentPath)) {
      this.error(`Agent '${agentName}' not found at ${agentPath}`)
    }

    if (!this.isGitRepo(agentPath)) {
      this.error(`'${agentName}' is not a Git repository. Run 'cast git init ${agentName}' first.`)
    }

    try {
      const git: SimpleGit = simpleGit(agentPath)

      // A clean tree that does not already track notes stays clean.
      // Tracked notes are removed even when nothing else changed, so
      // HEAD no longer contains memory/notes.md.
      const trackedNotes = memoryNotesAreTracked(agentPath)
      const status = await git.status()
      if (status.isClean() && !trackedNotes) {
        this.log('Nothing to commit - working tree is clean.')
        return
      }

      ensureMemoryDatabaseIgnored(agentPath)
      this.regenerateReadme(agentPath)

      await git.add('.')
      // git add updates a tracked notes file even after it is ignored.
      // Drop it again so the commit cannot record the working tree copy.
      const removedNotes = untrackMemoryNotes(agentPath) || trackedNotes

      const afterAdd = await git.status()
      if (afterAdd.isClean()) {
        this.log('Nothing to commit - working tree is clean.')
        return
      }

      const commitResult = await git.commit(message)

      this.log('')
      this.log(`Changes committed successfully!`)
      this.log(`  Commit: ${commitResult.commit}`)
      this.log(`  Files: ${commitResult.summary.changes} changed`)
      this.log(`  Insertions: +${commitResult.summary.insertions}`)
      this.log(`  Deletions: -${commitResult.summary.deletions}`)
      if (removedNotes) {
        this.log('  memory/notes.md is private and was left untracked.')
      }

    } catch (error: any) {
      this.error(`Failed to commit: ${error.message}`)
    }
  }
}