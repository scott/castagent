import {Args, Command} from '@oclif/core'
import * as fs from 'fs'
import * as os from 'os'
import * as path from 'path'
import simpleGit, {SimpleGit} from 'simple-git'
import * as yaml from 'yaml'
import {writeDefaultIgnoreFiles} from '../../lib/cast-ignore'

export default class GitInit extends Command {
  static description = 'Initialize a Git repository for an agent'

  static examples = [
    '<%= config.bin %> git init my-agent',
  ]

  static args = {
    agent: Args.string({description: 'Agent name', required: true}),
  }

  private getAgentsDir(): string {
    return path.join(os.homedir(), '.cast', 'agents')
  }

  private loadAgentConfig(agentPath: string): any {
    const configPath = path.join(agentPath, 'agent.yaml')
    if (fs.existsSync(configPath)) {
      const content = fs.readFileSync(configPath, 'utf-8')
      return yaml.parse(content) || {}
    }
    return {}
  }

  private generateReadme(agentName: string, config: any): string {
    const description = config.description || 'No description provided'
    const model = config.brain?.model || 'Not specified'
    const version = config.version || '1.0'
    const runtime = config.runtime?.python_version || '3.11'

    const builtinTools = config.tools?.builtin || []
    const mcpServers = config.tools?.mcp || []
    const customTools = config.tools?.custom || []

    const formatList = (items: any[]): string => {
      if (!items || items.length === 0) return 'None'
      return items.map(item => {
        if (typeof item === 'string') return `- ${item}`
        return `- ${item.name || item.server || JSON.stringify(item)}`
      }).join('\n')
    }

    return `# ${agentName}

${description}

## Configuration

- **Model:** ${model}
- **Runtime:** Python ${runtime}
- **Version:** ${version}

## Tools

### Built-in
${formatList(builtinTools)}

### MCP Servers
${formatList(mcpServers)}

### Custom
${formatList(customTools)}

## Setup

\`\`\`bash
# Clone this agent
cast clone <remote-url>

# Run the agent
cast dev ${agentName}
\`\`\`

## Files

- \`agent.yaml\` - Agent configuration
- \`instructions.md\` - System prompt
- \`tools/\` - Custom Python tools
- \`mcp/\` - MCP server configurations

---

*Generated by cast*
`
  }

  private createCastIgnore(agentPath: string): void {
    writeDefaultIgnoreFiles(agentPath)
  }

  private updateAgentYaml(agentPath: string): void {
    const configPath = path.join(agentPath, 'agent.yaml')
    const config = this.loadAgentConfig(agentPath)

    config.repository = {
      remote: 'origin',
      branch: 'main',
    }

    fs.writeFileSync(configPath, yaml.stringify(config))
  }

  async run(): Promise<void> {
    const {args} = await this.parse(GitInit)
    const agentName = args.agent

    const agentsDir = this.getAgentsDir()
    const agentPath = path.join(agentsDir, agentName)

    if (!fs.existsSync(agentPath)) {
      this.error(`Agent '${agentName}' not found at ${agentPath}`)
    }

    const gitDir = path.join(agentPath, '.git')
    if (fs.existsSync(gitDir)) {
      this.error(`Git repository already exists for '${agentName}'. Use 'cast git status ${agentName}' to see the current state.`)
    }

    this.log(`Initializing Git repository for agent '${agentName}'...`)

    try {
      const git: SimpleGit = simpleGit(agentPath)
      await git.init()

      this.createCastIgnore(agentPath)

      const config = this.loadAgentConfig(agentPath)
      const readmePath = path.join(agentPath, 'README.md')
      fs.writeFileSync(readmePath, this.generateReadme(agentName, config))

      this.updateAgentYaml(agentPath)

      await git.add('.')
      await git.commit(`Initial commit: ${agentName} v${config.version || '1.0'}`)

      this.log('')
      this.log(`Git repository initialized successfully!`)
      this.log('')
      this.log(`Next steps:`)
      this.log(`  - Add a remote: cast git remote ${agentName} create origin`)
      this.log(`  - Check status: cast git status ${agentName}`)
    } catch (error: any) {
      this.error(`Failed to initialize Git repository: ${error.message}`)
    }
  }
}