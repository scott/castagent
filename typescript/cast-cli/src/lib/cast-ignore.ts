import {execFileSync} from 'child_process'
import * as fs from 'fs'
import * as path from 'path'

/**
 * SQLite files MemoryStore writes under an agent's memory directory.
 * Keep this list in sync with the TUI /git init ignore text.
 */
export const MEMORY_DATABASE_IGNORE_LINES = [
  'memory/memory.db',
  'memory/memory.db-journal',
  'memory/memory.db-wal',
  'memory/memory.db-shm',
] as const

/**
 * Explicit remember writes memory/notes.md. Keep that file private so
 * git commit and git push cannot publish it.
 */
export const MEMORY_NOTES_IGNORE_LINES = [
  'memory/notes.md',
] as const

const MEMORY_GIT_IGNORE_LINES = [
  ...MEMORY_DATABASE_IGNORE_LINES,
  ...MEMORY_NOTES_IGNORE_LINES,
] as const

/**
 * Generated by `cast deploy --provider docker` inside the agent directory.
 * Anchored to the agent root so a nested Dockerfile or requirements.txt
 * stays tracked. Keep this list in sync with the TUI /git init ignore text.
 */
export const DOCKER_DEPLOY_IGNORE_LINES = [
  '/Dockerfile',
  '/docker-compose.yml',
  '/requirements.txt',
  '/.cast-runtime/',
] as const

export const CAST_IGNORE_LINES = [
  '.cast/versions/',
  'cast.db',
  '*.log',
  '.env',
  '__pycache__/',
  ...MEMORY_DATABASE_IGNORE_LINES,
  ...MEMORY_NOTES_IGNORE_LINES,
  ...DOCKER_DEPLOY_IGNORE_LINES,
] as const

export function defaultCastIgnoreContents(): string {
  return `${CAST_IGNORE_LINES.join('\n')}\n`
}

/** Write the default ignore rules to .castignore and .gitignore. */
export function writeDefaultIgnoreFiles(agentPath: string): void {
  const contents = defaultCastIgnoreContents()
  fs.writeFileSync(path.join(agentPath, '.castignore'), contents)
  fs.writeFileSync(path.join(agentPath, '.gitignore'), contents)
}

function isFile(filePath: string): boolean {
  try {
    return fs.statSync(filePath).isFile()
  } catch {
    return false
  }
}

export function appendMissingIgnoreLines(filePath: string, lines: readonly string[]): boolean {
  const original = fs.readFileSync(filePath, 'utf8')
  const present = new Set(
    original
      .split(/\r?\n/)
      .map(line => line.trim())
      .filter(line => line.length > 0 && !line.startsWith('#')),
  )
  const missing = lines.filter(line => !present.has(line))
  if (missing.length === 0) return false
  const prefix = original.length > 0 && !original.endsWith('\n') ? '\n' : ''
  fs.appendFileSync(filePath, `${prefix}${missing.join('\n')}\n`)
  return true
}

/**
 * True when memory/notes.md is in the index.
 * A gitignore rule does not drop a path that is already tracked.
 */
export function memoryNotesAreTracked(agentPath: string): boolean {
  if (!fs.existsSync(path.join(agentPath, '.git'))) return false
  try {
    const listed = execFileSync('git', ['ls-files', '--', ...MEMORY_NOTES_IGNORE_LINES], {
      cwd: agentPath,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    })
    return listed.split(/\r?\n/).some(line => line.trim() === MEMORY_NOTES_IGNORE_LINES[0])
  } catch {
    return false
  }
}

/**
 * Remove memory/notes.md from the index and leave the working tree file.
 * Returns true when the path was tracked.
 */
export function untrackMemoryNotes(agentPath: string): boolean {
  if (!memoryNotesAreTracked(agentPath)) return false
  execFileSync('git', ['rm', '--cached', '--ignore-unmatch', '--', ...MEMORY_NOTES_IGNORE_LINES], {
    cwd: agentPath,
    stdio: ['ignore', 'pipe', 'pipe'],
  })
  return true
}

/**
 * Keep memory/memory.db and memory/notes.md out of an agent Git repository.
 *
 * Git reads .gitignore. Older cast git init releases wrote the rules only
 * to .castignore, which Git does not read, so the runtime database showed
 * up as untracked. Notes were not listed at all. This appends the memory
 * database and notes rules to ignore files that already exist, and creates
 * .gitignore from .castignore when the repo has no .gitignore yet.
 * A notes file that is already tracked is removed from the index and left
 * on disk. The ignore rule alone does not do that.
 */
export function ensureMemoryDatabaseIgnored(agentPath: string): void {
  if (!fs.existsSync(path.join(agentPath, '.git'))) return

  const castIgnorePath = path.join(agentPath, '.castignore')
  const gitignorePath = path.join(agentPath, '.gitignore')

  if (isFile(castIgnorePath)) {
    appendMissingIgnoreLines(castIgnorePath, MEMORY_GIT_IGNORE_LINES)
  }

  if (isFile(gitignorePath)) {
    appendMissingIgnoreLines(gitignorePath, MEMORY_GIT_IGNORE_LINES)
  } else if (isFile(castIgnorePath)) {
    fs.copyFileSync(castIgnorePath, gitignorePath)
  } else {
    fs.writeFileSync(gitignorePath, `${MEMORY_GIT_IGNORE_LINES.join('\n')}\n`)
  }

  untrackMemoryNotes(agentPath)
}

/**
 * Keep generated Docker deploy files out of an agent Git repository.
 *
 * docker-compose.yml used to store the deployment bearer token in plain
 * text. Deploy no longer writes that token, and these paths stay ignored
 * so `cast git commit` cannot publish a local compose file or the copied
 * runtime. Existing ignore files gain the rules in place. A repository
 * with no .gitignore yet gets one.
 */
export function ensureDockerDeployArtifactsIgnored(agentPath: string): void {
  const castIgnorePath = path.join(agentPath, '.castignore')
  const gitignorePath = path.join(agentPath, '.gitignore')
  const hasGit = fs.existsSync(path.join(agentPath, '.git'))

  if (isFile(castIgnorePath)) {
    appendMissingIgnoreLines(castIgnorePath, DOCKER_DEPLOY_IGNORE_LINES)
  }

  if (isFile(gitignorePath)) {
    appendMissingIgnoreLines(gitignorePath, DOCKER_DEPLOY_IGNORE_LINES)
    return
  }

  if (!hasGit) return

  if (isFile(castIgnorePath)) {
    fs.copyFileSync(castIgnorePath, gitignorePath)
    return
  }

  fs.writeFileSync(gitignorePath, `${DOCKER_DEPLOY_IGNORE_LINES.join('\n')}\n`)
}
