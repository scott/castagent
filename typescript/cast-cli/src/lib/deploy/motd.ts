import {execDigitalOceanSsh} from './ssh-hostkey'

/**
 * Context for building the host MOTD. Values are substituted into the
 * template at deploy/upgrade time and written to the host filesystem.
 */
export interface MotdContext {
  /** Agent name (e.g. "email-agent") */
  agentName: string
  /** Droplet's public IP (used for the A2A URL) */
  dropletIp: string
  /** Deployed semver, if known. Falls back to a dash. */
  deployedVersion?: string | null
  /** Override for the A2A URL. Defaults to `http://{dropletIp}:8080`. */
  a2aUrl?: string
  /**
   * Whether the on-host TUI (`cast-tui` command) is bundled in this
   * agent's image. When `true`, the MOTD tells users to run `cast-tui`
   * for a chat REPL. When `false` (or unset), the MOTD omits the TUI
   * instructions so users aren't told to run a command that doesn't
   * exist in the container.
   *
   * Defaults to `false` for safety — if a caller doesn't know whether
   * the TUI is present, it's better to omit the hint than to lie.
   */
  onHostTui?: boolean
}

function resolveA2aUrl(ctx: MotdContext): string {
  return ctx.a2aUrl ?? `http://${ctx.dropletIp}:8080`
}

/**
 * Build the contents of /etc/motd — displayed by pam_motd BEFORE the
 * login shell starts. This is what users see on SSH login.
 *
 * When `ctx.onHostTui === true`, the banner includes the
 * `docker exec ... && cast-tui` instructions for chatting on the
 * host. When false/unset, the banner only points at the A2A URL —
 * it never mentions a command that isn't installed in the container.
 */
export function buildHostMotd(ctx: MotdContext): string {
  const a2a = resolveA2aUrl(ctx)
  const version = ctx.deployedVersion ? `v${ctx.deployedVersion}` : null
  const agentLine = version
    ? `${ctx.agentName}  ${version}`
    : ctx.agentName
  const metaLine = `A2A: ${a2a}`

  // Build a box that fits the hostname + version comfortably
  const innerWidth = Math.max(agentLine.length + 6, metaLine.length + 6, 50)
  const pad = (s: string): string => '  ' + s.padEnd(innerWidth - 2)
  const border = '═'.repeat(innerWidth)

  const lines: string[] = [
    `╔${border}╗`,
    `║${pad(agentLine)}║`,
    `║${pad(metaLine)}║`,
    `╚${border}╝`,
    '',
  ]

  if (ctx.onHostTui) {
    // On-host TUI is bundled — show the docker-exec + cast-tui path.
    lines.push(
      'To chat with this agent:',
      '  1. Get a shell in the container:  docker exec -it cast-agent bash',
      '  2. Start the on-host TUI:          cast-tui',
      '',
    )
  } else {
    // TUI is not bundled — point users at the A2A HTTP API only.
    // The "A2A:" line in the box already shows the URL.
    lines.push(
      'Talk to this agent via the A2A API:',
      `  curl ${a2a}/`,
      '',
    )
  }

  lines.push('To view logs:  docker logs -f cast-agent', '')
  return lines.join('\n')
}

/**
 * Build the contents of /etc/profile.d/cast.sh — sourced by login
 * shells to print connection info after the user lands. Complements
 * the /etc/motd banner with a shorter, in-shell reminder.
 *
 * When `ctx.onHostTui === true`, the reminder includes a `cast-tui`
 * hint. When false/unset, only the agent name + A2A URL is shown.
 */
export function buildProfileSnippet(ctx: MotdContext): string {
  const a2a = resolveA2aUrl(ctx)
  const version = ctx.deployedVersion ? `v${ctx.deployedVersion}` : null
  const agentLabel = version
    ? `${ctx.agentName} ${version}`
    : ctx.agentName

  // Pick the right "Run:" line based on whether the TUI is present.
  // If the TUI isn't bundled, mentioning `cast-tui` would tell users
  // to run a command that doesn't exist — so we just point at the
  // A2A URL.
  const runLine = ctx.onHostTui
    ? 'Run:  docker exec -it cast-agent bash  &&  cast-tui'
    : `Talk to this agent via the A2A API at: ${a2a}`

  return [
    '# Cast agent info (auto-generated by `cast deploy` / `cast upgrade`)',
    'if [ -n "$PS1" ] && [ -z "${CAST_PROFILE_SHOWN:-}" ]; then',
    '  export CAST_PROFILE_SHOWN=1',
    `  echo ""`,
    `  echo "${agentLabel}  ·  A2A: ${a2a}"`,
    `  echo "${runLine}"`,
    `  echo ""`,
    'fi',
    '',
  ].join('\n')
}

/**
 * Build the contents of the cloud-init baseline /etc/motd. This is
 * written ONCE at droplet creation. The real MOTD is overwritten by
 * the deploy/upgrade steps, but this ensures the user sees something
 * cast-related on first SSH even before any deploy has run.
 */
export function buildCloudInitBaselineMotd(): string {
  return [
    'Cast droplet initialized.',
    'Run `cast deploy <agent>` from your local machine to complete setup.',
    'A full MOTD will be written on first deploy.',
    '',
  ].join('\n')
}

/**
 * Write the host MOTD and login-shell snippet over SSH. The content is
 * base64-encoded before being sent so we never have to worry about
 * shell escaping inside the multi-line strings.
 * The session uses the pinned droplet host key.
 *
 * Writes:
 *   - /etc/motd             (displayed by pam_motd on SSH login)
 *   - /etc/profile.d/cast.sh  (sourced by login shells)
 *
 * Failures are surfaced via the returned stderr but do not throw —
 * the caller can decide how to handle a failed MOTD write.
 */
export async function writeHostMotdOverSsh(
  ip: string,
  ctx: MotdContext,
): Promise<{motdStderr: string; profileStderr: string}> {
  const hostMotd = buildHostMotd(ctx)
  const profileSnippet = buildProfileSnippet(ctx)
  const motdB64 = Buffer.from(hostMotd, 'utf8').toString('base64')
  const profileB64 = Buffer.from(profileSnippet, 'utf8').toString('base64')

  const motdResult = await execDigitalOceanSsh(
    ip,
    `echo '${motdB64}' | base64 -d > /etc/motd && chmod 644 /etc/motd`,
    {silent: true},
  )

  const profileResult = await execDigitalOceanSsh(
    ip,
    `echo '${profileB64}' | base64 -d > /etc/profile.d/cast.sh && chmod 755 /etc/profile.d/cast.sh`,
    {silent: true},
  )

  return {
    motdStderr: motdResult.stderr,
    profileStderr: profileResult.stderr,
  }
}
